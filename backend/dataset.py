import sqlite3
from werkzeug.security import generate_password_hash
from database import DB_PATH


def initialize_dataset():
    """Create missing shared accounts without overwriting existing data."""

    with sqlite3.connect(DB_PATH) as conn:
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")

        # Create faculty accounts first
        for faculty in FACULTY_MEMBERS:
            account = conn.execute("""
                SELECT id, name, email, role
                FROM users
                WHERE id = ? OR email = ?
            """, (faculty["id"], faculty["email"])).fetchall()

            if account:
                if len(account) != 1:
                    raise ValueError(
                        f"Conflicting faculty account: {faculty['email']}"
                    )

                existing = account[0]

                if (
                    existing["id"] != faculty["id"]
                    or existing["name"] != faculty["name"]
                    or existing["email"] != faculty["email"]
                    or existing["role"] != "faculty"
                ):
                    raise ValueError(
                        f"Faculty account conflict: {faculty['email']}"
                    )

                continue

            conn.execute("""
                INSERT INTO users (id, name, email, password_hash, role)
                VALUES (?, ?, ?, ?, 'faculty')
            """, (
                faculty["id"],
                faculty["name"],
                faculty["email"],
                generate_password_hash(FACULTY_PASSWORD)
            ))

        # Create student accounts
        for student_id, name, email, faculty_id in STUDENTS:
            account = conn.execute("""
                SELECT id, name, email, role, faculty_id
                FROM users
                WHERE id = ? OR email = ?
            """, (student_id, email)).fetchall()

            if account:
                if len(account) != 1:
                    raise ValueError(
                        f"Conflicting student account: {email}"
                    )

                existing = account[0]

                if (
                    existing["id"] != student_id
                    or existing["name"] != name
                    or existing["email"] != email
                    or existing["role"] != "student"
                ):
                    raise ValueError(
                        f"Student account conflict: {email}"
                    )

                if existing["faculty_id"] is None:
                    conn.execute("""
                        UPDATE users
                        SET faculty_id = ?
                        WHERE id = ? AND faculty_id IS NULL
                    """, (faculty_id, student_id))
                elif existing["faculty_id"] != faculty_id:
                    raise ValueError(
                        f"Faculty assignment conflict for {email}"
                    )

                continue

            conn.execute("""
                INSERT INTO users (
                    id, name, email, password_hash, role, faculty_id
                )
                VALUES (?, ?, ?, ?, 'student', ?)
            """, (
                student_id,
                name,
                email,
                generate_password_hash(STUDENT_PASSWORD),
                faculty_id
            ))

    print("MedLearn AI shared dataset initialized successfully.")

